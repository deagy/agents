# Identity, markers, labels (spec §1)
# --------------------------------------------------------------------------


def compute_marker(task_id: str, gate_id: str, item_key: str) -> str:
    """Hashed identifier (never the raw `task_id`, which is operator-chosen
    and may be sensitive, and the target GitLab project may be more
    widely visible than the source repo)."""
    digest = hashlib.sha256(f"{task_id}\x00{gate_id}\x00{item_key}".encode("utf-8")).hexdigest()
    return digest[:16]


def item_label(marker: str) -> str:
    label = f"agentic-sdlc-item-{marker}"
    if not _LABEL_CHARSET_RE.fullmatch(label):
        raise RequirementIssuesError(f"computed label {label!r} violates the [a-z0-9-] label charset")
    return label


def task_hash(task_id: str) -> str:
    return hashlib.sha256(task_id.encode("utf-8")).hexdigest()[:16]


