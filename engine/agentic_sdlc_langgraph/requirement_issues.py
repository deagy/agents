def _empty_ledger(task_id: str) -> dict[str, Any]:
    return {
        "schema_version": LEDGER_SCHEMA_VERSION,
        "task_id": task_id,
        "gate_id": None,
        "project": None,
        "bot_username": None,
        "mocked": False,
        "entries": {},
    }


def read_ledger(root: Path, task_id: str) -> dict[str, Any]:
    path = _requirement_ledger_path(Path(root), task_id)
    if not path.is_file():
        return _empty_ledger(task_id)
    return json.loads(path.read_text(encoding="utf-8"))


def write_ledger(root: Path, task_id: str, ledger: dict[str, Any]) -> None:
    """Exact durable-write sequence from spec §3.7: full-file rewrite,
    same-filesystem tmp file, fsync data, atomic rename, fsync the
    containing directory so the rename itself survives power loss."""
    path = _requirement_ledger_path(Path(root), task_id)
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = (json.dumps(ledger, indent=2, sort_keys=True) + "\n").encode("utf-8")

    fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=".requirement-issues.", suffix=".tmp")
    try:
        os.write(fd, payload)
        os.fsync(fd)
    finally:
        os.close(fd)
    os.chmod(tmp_name, 0o600)
    os.replace(tmp_name, path)

    dir_fd = os.open(str(path.parent), os.O_DIRECTORY)
    try:
        os.fsync(dir_fd)
    finally:
        os.close(dir_fd)


# --------------------------------------------------------------------------
# Whole-run lock (spec §3.0 step 6)
# --------------------------------------------------------------------------


def acquire_lock(root: Path, task_id: str, *, break_lock: bool) -> Path:
    path = _requirement_lock_path(Path(root), task_id)
    path.parent.mkdir(parents=True, exist_ok=True)

    if break_lock and path.is_file():
        path.unlink(missing_ok=True)

    try:
        fd = os.open(str(path), os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    except FileExistsError:
        holder = "(unreadable)"
        try:
            holder = path.read_text(encoding="utf-8")
        except OSError:
            pass
        raise RequirementIssuesBlocked(
            f"requirement-issues.lock is already held -- pass --break-lock to override "
            f"(never auto-broken on timeout). Holder:\n{holder}"
        ) from None

    payload = json.dumps(
        {"pid": os.getpid(), "host": socket.gethostname(), "started_at": _now()}, indent=2
    )
    os.write(fd, payload.encode("utf-8"))
    os.close(fd)
    return path


def release_lock(path: Path) -> None:
    try:
        path.unlink()
    except FileNotFoundError:
        pass


