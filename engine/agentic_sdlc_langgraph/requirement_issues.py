def compute_plan_digest(
    *,
    task_id: str,
    gate_id: str,
    project: str,
    items_raw: bytes,
    item_keys: list[str],
    item_hashes: dict[str, str],
    run_halted: bool,
    required_reentry_gate: str | None,
    gate_status: str | None,
    re_entry_count: int,
) -> str:
    payload = {
        "task_id": task_id,
        "gate_id": gate_id,
        "project": project,
        "items_digest": "sha256:" + hashlib.sha256(items_raw).hexdigest(),
        "item_keys": list(item_keys),
        "item_hashes": dict(item_hashes),
        "eligibility": {
            "run_halted": run_halted,
            "required_reentry_gate": required_reentry_gate,
            "publishable": gate_status not in {"blocked", "invalidated"},
            "re_entry_count": re_entry_count,
        },
    }
    return fingerprint(payload)


def check_publish_eligibility(
    *, run_halted: bool, required_reentry_gate: str | None, gate_status: str | None
) -> None:
    if run_halted:
        raise RequirementIssuesBlocked(
            "task run is halted (mutation-gate rejection) -- cannot publish requirement issues"
        )
    if required_reentry_gate:
        raise RequirementIssuesBlocked(
            f"gate has a pending required_reentry_gate={required_reentry_gate!r} -- resolve reentry first"
        )
    if gate_status in {"blocked", "invalidated"}:
        raise RequirementIssuesBlocked(f"gate status {gate_status!r} is not publish-eligible")


