# Per-item existence check / create+verify / drift report (spec §3.4-3.6)
# --------------------------------------------------------------------------


def _validate_matched_issue(issue: dict[str, Any], si: SanitizedItem, item_key: str) -> None:
    """Validate a *reused* (already-existing) matched issue's labels.

    Deliberately containment, not exact-set-equality, unlike the
    post-creation verification in `_process_item` (which *does* require
    `set(labels) == {FIXED_LABEL, ITEM_LABEL}` exactly, since it is
    checking an issue this run itself just created and nothing else
    should have touched it yet). A long-lived *reused* issue may
    legitimately accumulate other labels over its life (triage, priority,
    team, ...) between re-entries -- requiring exact-set-equality here
    would break normal reuse for any issue a human has ever additionally
    labeled. What must still hold, and is still checked exactly, is that
    the two anchor labels (`FIXED_LABEL`, this item's own `ITEM_LABEL`)
    are both present and that no *other* `agentic-sdlc-item-*` label is
    present (which would indicate a mismatched/poisoned issue, not benign
    accumulated labeling).
    """
    labels = set(issue.get("labels") or [])
    if FIXED_LABEL not in labels:
        raise RequirementIssuesBlocked(
            f"item {item_key!r}: matched issue is missing the {FIXED_LABEL!r} anchor label"
        )
    if si.label not in labels:
        raise RequirementIssuesBlocked(
            f"item {item_key!r}: matched issue is missing its own item label {si.label!r}"
        )
    foreign = {l for l in labels if l.startswith("agentic-sdlc-item-") and l != si.label}
    if foreign:
        raise RequirementIssuesBlocked(
            f"item {item_key!r}: matched issue carries a foreign item label {sorted(foreign)} "
            "-- possible mismatch/poisoned issue"
        )


def _process_item(
    root: Path, task_id: str, project: str, si: SanitizedItem, ledger: dict[str, Any], *,
    mocked: bool, bot_username: str,
) -> dict[str, Any]:
    try:
        return _process_item_inner(root, task_id, project, si, ledger, mocked=mocked, bot_username=bot_username)
    except (RequirementIssuesError, RequirementIssuesBlocked):
        raise
    except ValueError as exc:
        # Plain `ValueError` from `gitlab_issue.py` (a failed `glab`
        # call, malformed response, ...) is a structural failure, not a
        # human-resolvable ambiguity -- map it to exit code 1, not 2.
        raise RequirementIssuesError(f"item {si.key!r}: {exc}") from exc


def _process_item_inner(
    root: Path, task_id: str, project: str, si: SanitizedItem, ledger: dict[str, Any], *,
    mocked: bool, bot_username: str,
) -> dict[str, Any]:
    prior_entry = ledger["entries"].get(si.key)

    existing = gitlab_issue.search_gitlab_issues_by_labels(project, [FIXED_LABEL, si.label])
    if len(existing) > 1:
        raise RequirementIssuesBlocked(
            f"item {si.key!r}: {len(existing)} issues matched labels "
            f"[{FIXED_LABEL}, {si.label}] -- ambiguous identity, needs human resolution"
        )

    if len(existing) == 1:
        issue = existing[0]
        _validate_matched_issue(issue, si, si.key)
        iid = issue.get("iid")
        uri = gitlab_issue.gitlab_issue_uri(project, iid)

        # Author check on reuse, mirroring the create path's
        # post-creation verification. The item label is deterministic
        # and not secret (see `compute_marker`'s docstring -- hashing is
        # to avoid leaking `task_id` externally, not to make the label
        # unguessable), so without this check any Reporter+ contributor
        # to the target project could pre-create an issue carrying
        # `[FIXED_LABEL, item_label]` and have this tool silently adopt
        # it as canonical -- worse than the accepted quick-action gap,
        # since none of the creation-time controls (sanitization,
        # post-creation verification) ever ran against that content at
        # all. A follow-up authoritative fetch (not just the search
        # response, whose exact field set isn't guaranteed here) is used
        # so `author_username`/`state` are both read from the same
        # verification shape the create path already trusts.
        verification = gitlab_issue.fetch_gitlab_issue_verification(project, iid)
        verified_author = (verification.get("author_username") or "").lower()
        if verified_author != bot_username.lower():
            entry = {
                "item_key": si.key,
                "marker": si.marker,
                "status": "suspect",
                "issue_uri": uri,
                "issue_state": verification.get("state"),
                "content_hash": si.content_hash,
                "prior_title": si.raw_title,
                "prior_description": si.raw_description,
                "attempted_at": _now(),
                "recorded_at": _now(),
                "detail": (
                    f"matched issue author {verification.get('author_username')!r} does not match "
                    f"the verified bot identity {bot_username!r} -- refusing to reuse a "
                    "possibly attacker-created issue"
                ),
            }
            ledger["entries"][si.key] = entry
            ledger["mocked"] = mocked
            write_ledger(root, task_id, ledger)
            raise RequirementIssuesBlocked(
                f"item {si.key!r}: matched issue's author does not match the verified bot identity "
                "-- refusing to reuse, needs human resolution"
            )

        state = verification.get("state")

        if prior_entry is None:
            drift = "reused (drift-unknown)"
        elif prior_entry.get("content_hash") != si.content_hash:
            drift = "changed_content"
        else:
            drift = None
        if state == "closed":
            drift = "reused (closed)" if drift is None else f"{drift}; reused (closed)"

        entry = {
            "item_key": si.key,
            "marker": si.marker,
            "status": "reused",
            "issue_uri": uri,
            "issue_state": state,
            "content_hash": si.content_hash,
            "prior_title": si.raw_title,
            "prior_description": si.raw_description,
            "attempted_at": _now(),
            "recorded_at": _now(),
            "detail": drift,
        }
        ledger["entries"][si.key] = entry
        ledger["mocked"] = mocked
        write_ledger(root, task_id, ledger)
        return {
            "item_key": si.key,
            "status": "reused",
            "issue_uri": uri,
            "issue_state": state,
            "drift": drift,
            "previous_title": prior_entry.get("prior_title") if prior_entry else None,
            "previous_description": prior_entry.get("prior_description") if prior_entry else None,
        }

    # --- create path (spec §3.5) -----------------------------------------
    entry = {
        "item_key": si.key,
        "marker": si.marker,
        "status": "creating",
        "issue_uri": None,
        "issue_state": None,
        "content_hash": si.content_hash,
        "prior_title": si.raw_title,
        "prior_description": si.raw_description,
        "attempted_at": _now(),
        "recorded_at": None,
        "detail": None,
    }
    ledger["entries"][si.key] = entry
    ledger["mocked"] = mocked
    write_ledger(root, task_id, ledger)  # BEFORE the API call, per spec.

    iid = gitlab_issue.create_gitlab_issue(project, si.title, si.body, [FIXED_LABEL, si.label])
    uri = gitlab_issue.gitlab_issue_uri(project, iid)
    verification = gitlab_issue.fetch_gitlab_issue_verification(project, iid)

    failures: list[str] = []
    if verification.get("title") != si.title:
        failures.append("title")
    if verification.get("state") != "opened":
        failures.append("state")
    if set(verification.get("labels") or []) != {FIXED_LABEL, si.label}:
        failures.append("labels")
    if verification.get("assignee_count", 0) != 0:
        failures.append("assignee_count")
    if verification.get("confidential", False) is not False:
        failures.append("confidential")
    if verification.get("project_path") != project:
        failures.append("project_path")
    verified_author = verification.get("author_username") or ""
    if verified_author.lower() != bot_username.lower():
        failures.append("author_username")

    if failures:
        entry = dict(entry)
        entry["status"] = "suspect"
        entry["issue_uri"] = uri
        entry["issue_state"] = verification.get("state")
        entry["recorded_at"] = _now()
        entry["detail"] = f"post-creation verification failed: {', '.join(failures)}"
        ledger["entries"][si.key] = entry
        write_ledger(root, task_id, ledger)
        raise RequirementIssuesBlocked(
            f"item {si.key!r}: post-creation verification failed ({', '.join(failures)}) "
            "-- aborting the entire run immediately"
        )

    entry = dict(entry)
    entry["status"] = "created"
    entry["issue_uri"] = uri
    entry["issue_state"] = verification.get("state")
    entry["recorded_at"] = _now()
    ledger["entries"][si.key] = entry
    write_ledger(root, task_id, ledger)
    return {"item_key": si.key, "status": "created", "issue_uri": uri, "issue_state": verification.get("state"), "drift": None}


# --------------------------------------------------------------------------
# Top-level orchestration (spec §3.0-§3.7)
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class Eligibility:
    run_halted: bool
    required_reentry_gate: str | None
    gate_status: str | None
    re_entry_count: int
    classification: str | None


def run(
    *,
    root: Path,
    task_id: str,
    project: str,
    items_source: str,
    as_bot: str,
    apply: bool,
    plan_digest: str | None,
    allow_classification: str | None,
    max_items: int,
    break_lock: bool,
    i_know_this_is_mocked: bool,
    get_eligibility: Callable[[], Eligibility],
) -> dict[str, Any]:
    """Orchestrate `create-requirement-issues`, dry-run or apply.

    `get_eligibility` is a caller-supplied callback (see `cli.py`) that
    fetches live `run_halted`/`required_reentry_gate`/gate `status`/
    `re_entry_history` length/`classification` from the compiled graph's
    checkpointed state -- this module never imports `graph.py`/`runtime`'s
    graph-building machinery itself, keeping it backend-neutral and
    unreachable from `graph.py`'s dispatch (see module docstring).
    Re-invoked before every item in apply mode so a concurrent
    `reenter`/`invalidate` mid-loop is caught at the next item boundary.

    Raises `RequirementIssuesError` (CLI exit 1) or
    `RequirementIssuesBlocked` (CLI exit 2) on any preflight/sanitization/
    verification failure.
    """
    root = Path(root)
    try:
        raw = read_items_source(items_source)
    except OSError as exc:
        # A nonexistent/unreadable --items file (FileNotFoundError,
        # PermissionError, IsADirectoryError, ...) must abort cleanly
        # the same way a malformed-JSON --items file already does
        # (`parse_items_file` below), not surface as a raw traceback.
        raise RequirementIssuesError(f"unable to read --items {items_source!r}: {exc}") from exc
    items_file = parse_items_file(raw, max_items)
    gate_id = items_file.gate_id

    sanitized_items = sanitize_items(task_id, gate_id, items_file.items)
    item_keys = [i.key for i in items_file.items]
    item_hashes = {i.key: i.content_hash for i in items_file.items}

    def _digest_for(eligibility: Eligibility) -> str:
        return compute_plan_digest(
            task_id=task_id,
            gate_id=gate_id,
            project=project,
            items_raw=raw,
            item_keys=item_keys,
            item_hashes=item_hashes,
            run_halted=eligibility.run_halted,
            required_reentry_gate=eligibility.required_reentry_gate,
            gate_status=eligibility.gate_status,
            re_entry_count=eligibility.re_entry_count,
        )

    eligibility = get_eligibility()
    digest = _digest_for(eligibility)

    if allow_classification is None or allow_classification != eligibility.classification:
        raise RequirementIssuesError(
            "--allow-classification must be supplied and exactly match the task's classification "
            f"(got {allow_classification!r}, task classification is {eligibility.classification!r})"
        )

    check_publish_eligibility(
        run_halted=eligibility.run_halted,
        required_reentry_gate=eligibility.required_reentry_gate,
        gate_status=eligibility.gate_status,
    )

    mocked = bool(os.environ.get(gitlab_issue.ISSUE_CREATE_MOCK_ENV_VAR))

    if not apply:
        return {
            "mode": "dry-run",
            "plan_digest": digest,
            "gate_id": gate_id,
            "project": project,
            "mocked": mocked,
            "items": [
                {
                    "item_key": si.key,
                    "marker": si.marker,
                    "label": si.label,
                    "content_hash": si.content_hash,
                }
                for si in sanitized_items
            ],
        }

    if plan_digest is None:
        raise RequirementIssuesError("--apply requires --plan-digest (from a prior --dry-run)")
    if plan_digest != digest:
        raise RequirementIssuesBlocked(
            f"--plan-digest mismatch: recomputed {digest!r} != supplied {plan_digest!r} "
            "-- state changed since the --dry-run this digest came from; re-run --dry-run"
        )

    if mocked and not i_know_this_is_mocked:
        raise RequirementIssuesError(
            f"{gitlab_issue.ISSUE_CREATE_MOCK_ENV_VAR} is set but --i-know-this-is-mocked was not "
            "passed -- refusing to --apply against a mocked GitLab backend"
        )

    try:
        verified_username = gitlab_issue.verify_gitlab_identity(as_bot)
    except ValueError as exc:
        raise RequirementIssuesError(str(exc)) from exc

    lock_path = acquire_lock(root, task_id, break_lock=break_lock)
    try:
        ledger = read_ledger(root, task_id)
        ledger["schema_version"] = LEDGER_SCHEMA_VERSION
        ledger["task_id"] = task_id
        ledger["gate_id"] = gate_id
        ledger["project"] = project
        ledger["bot_username"] = verified_username
        ledger["mocked"] = mocked
        ledger.setdefault("entries", {})

        results = []
        for si in sanitized_items:
            fresh_digest = _digest_for(get_eligibility())
            if fresh_digest != plan_digest:
                raise RequirementIssuesBlocked(
                    f"plan digest changed before item {si.key!r} (a reenter/invalidate happened "
                    "concurrently) -- aborting remaining items; already-created issues are unaffected"
                )
            result = _process_item(
                root, task_id, project, si, ledger, mocked=mocked, bot_username=verified_username
            )
            results.append(result)

        return {
            "mode": "apply",
            "plan_digest": digest,
            "gate_id": gate_id,
            "project": project,
            "mocked": mocked,
            "bot_username": verified_username,
            "results": results,
        }
    finally:
        release_lock(lock_path)
