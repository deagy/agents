# Item loading/validation (spec §2)
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class Item:
    key: str
    title: str
    description: str
    content_hash: str  # fingerprint({"title": ..., "description": ...})


@dataclass(frozen=True)
class ItemsFile:
    schema_version: int
    gate_id: str
    items: list[Item]


def read_items_source(value: str) -> bytes:
    """Mirrors `cli.py`'s `_load_decision`: `value` is a file path, or
    `-` to read from stdin."""
    if value == "-":
        return sys.stdin.buffer.read()
    return Path(value).read_bytes()


def parse_items_file(raw: bytes, max_items: int) -> ItemsFile:
    try:
        payload = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise RequirementIssuesError(f"--items is not valid JSON: {exc}") from exc
    if not isinstance(payload, dict):
        raise RequirementIssuesError("--items must contain a JSON object")

    schema_version = payload.get("schema_version")
    if schema_version != ITEMS_SCHEMA_VERSION:
        raise RequirementIssuesError(
            f"--items schema_version must be {ITEMS_SCHEMA_VERSION}, got {schema_version!r}"
        )

    gate_id = payload.get("gate_id")
    if gate_id != "G2":
        raise RequirementIssuesError(f"--items gate_id must be 'G2' in v1, got {gate_id!r}")

    raw_items = payload.get("items")
    if not isinstance(raw_items, list) or not raw_items:
        raise RequirementIssuesError("--items must contain a non-empty 'items' array")
    if len(raw_items) > max_items:
        raise RequirementIssuesError(
            f"--items has {len(raw_items)} items, exceeding --max-items {max_items} -- "
            "refusing rather than truncating"
        )

    seen_keys: set[str] = set()
    items: list[Item] = []
    for entry in raw_items:
        if not isinstance(entry, dict):
            raise RequirementIssuesError("each item in --items must be a JSON object")
        key = entry.get("key")
        title = entry.get("title")
        description = entry.get("description")
        if not isinstance(key, str) or not _ITEM_KEY_RE.fullmatch(key):
            raise RequirementIssuesError(f"item key {key!r} does not match the required pattern")
        if key in seen_keys:
            raise RequirementIssuesError(f"duplicate item key {key!r} in --items")
        seen_keys.add(key)
        if not isinstance(title, str) or not isinstance(description, str):
            raise RequirementIssuesError(f"item {key!r} must have string 'title' and 'description' fields")
        content_hash = fingerprint({"title": title, "description": description})
        items.append(Item(key=key, title=title, description=description, content_hash=content_hash))

    return ItemsFile(schema_version=schema_version, gate_id=gate_id, items=items)


# --------------------------------------------------------------------------
# Sanitization (spec §3.2, §3.3) -- reject and abort, never substitute.
# Deliberately NOT `agents._sanitized_artifact_field`, which substitutes a
# default on failure -- wrong here, since that would still create an
# externally-visible issue with a placeholder title.
# --------------------------------------------------------------------------


def sanitize_title(title: str, item_key: str) -> str:
    normalized = unicodedata.normalize("NFKC", title)
    for ch in normalized:
        if not (0x20 <= ord(ch) <= 0x7E):
            raise RequirementIssuesError(
                f"item {item_key!r}: title contains a non-printable-ASCII character (U+{ord(ch):04X})"
            )
    stripped = normalized.strip()
    if not stripped:
        raise RequirementIssuesError(f"item {item_key!r}: title is empty after normalization/strip")
    if stripped[0] in ("-", "/"):
        raise RequirementIssuesError(f"item {item_key!r}: title must not start with '-' or '/'")
    if len(stripped) > 200:
        raise RequirementIssuesError(f"item {item_key!r}: title exceeds 200 characters")
    return stripped


def _has_lone_surrogate(text: str) -> bool:
    return any(0xD800 <= ord(ch) <= 0xDFFF for ch in text)


def _neutralize_references(text: str) -> str:
    """Neutralize `@mentions` and `owner/repo#N` / bare `#N` cross-refs by
    inserting a zero-width space (U+200B) so GitLab's autolinking never
    fires, while keeping the description human-readable. One approach,
    applied consistently to both mention and cross-ref forms."""

    zwsp = "\u200b"

    def _mention(match: re.Match[str]) -> str:
        return "@" + zwsp + match.group(1)

    def _crossref(match: re.Match[str]) -> str:
        prefix = match.group(1) or ""
        return f"{prefix}#{zwsp}{match.group(2)}"

    text = _MENTION_RE.sub(_mention, text)
    text = _CROSS_REF_RE.sub(_crossref, text)
    return text


def sanitize_description(description: str, item_key: str) -> str:
    # 1. Reject forbidden control/line-separator characters and lone
    # surrogates outright -- this is what makes `splitlines()` and a naive
    # `split("\n")` agree, closing the bypass at the source (see module
    # docstring / `_FORBIDDEN_DESC_CHARS`).
    for ch in description:
        if ch in _FORBIDDEN_DESC_CHARS:
            raise RequirementIssuesError(
                f"item {item_key!r}: description contains a forbidden control/line-separator "
                f"character (U+{ord(ch):04X})"
            )
    if _has_lone_surrogate(description):
        raise RequirementIssuesError(f"item {item_key!r}: description contains a lone Unicode surrogate")

    # 2. Reject GitLab quick-action injection: any line whose stripped
    # form starts with "/" (e.g. "/assign @victim", "/confidential").
    lines = description.splitlines()
    for line in lines:
        if line.strip().startswith("/"):
            raise RequirementIssuesError(
                f"item {item_key!r}: description contains a line starting with '/' "
                "(GitLab quick-action injection risk)"
            )

    # 3. Reject the reserved provenance-banner/ref-line prefixes anywhere
    # in operator-supplied content -- only this module ever emits them.
    for line in lines:
        if line.startswith(_REF_LINE_PREFIX) or line.startswith(_PROVENANCE_BANNER):
            raise RequirementIssuesError(
                f"item {item_key!r}: description contains the reserved provenance/ref-line prefix"
            )

    # 4. Neutralize @mentions and cross-references.
    sanitized = _neutralize_references(description)

    # 5. Length cap, checked after neutralization (which can only grow the
    # string, never shrink it below the raw length).
    if len(sanitized) > 8000:
        raise RequirementIssuesError(f"item {item_key!r}: description exceeds 8000 characters")

    return sanitized


def _fence_length(text: str) -> int:
    longest = 0
    current = 0
    for ch in text:
        if ch == "`":
            current += 1
            longest = max(longest, current)
        else:
            current = 0
    return max(3, longest + 1)


def render_body(task_id: str, gate_id: str, marker: str, sanitized_description: str) -> str:
    """Spec §4 body template. `<task-hash>` is `sha256(task_id)[:16]` --
    never the raw task_id. The `ref` line is a human-readable hint only;
    the *label* (see `item_label`) is the actual trust anchor -- nothing
    here or in `requirement_issues.py`'s existence check ever searches on
    this line's text."""
    fence = "`" * _fence_length(sanitized_description)
    return (
        f"{_PROVENANCE_BANNER}\n"
        f"{_REF_LINE_PREFIX}{task_hash(task_id)}/{gate_id}/{marker}\n"
        "\n"
        f"{fence}\n"
        f"{sanitized_description}\n"
        f"{fence}\n"
    )


@dataclass(frozen=True)
class SanitizedItem:
    key: str
    raw_title: str
    raw_description: str
    title: str
    body: str
    marker: str
    label: str
    content_hash: str


def sanitize_items(task_id: str, gate_id: str, items: list[Item]) -> list[SanitizedItem]:
    """Sanitize every item up front, both dry-run and apply. A rejected
    title/description aborts the whole run before any GitLab call is
    made, naming the offending item key -- never a partial run, never a
    substituted placeholder."""
    result = []
    for item in items:
        marker = compute_marker(task_id, gate_id, item.key)
        label = item_label(marker)
        title = sanitize_title(item.title, item.key)
        description = sanitize_description(item.description, item.key)
        body = render_body(task_id, gate_id, marker, description)
        result.append(
            SanitizedItem(
                key=item.key,
                raw_title=item.title,
                raw_description=item.description,
                title=title,
                body=body,
                marker=marker,
                label=label,
                content_hash=item.content_hash,
            )
        )
    return result


