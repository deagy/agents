"""`create-requirement-issues` / `list-requirement-issues` (Stage A,
GitLab-only): back a G2 Requirements Baseline item list with real GitLab
issues, idempotently, with the forge itself (queried by label) as the
source of truth for "does this item already have an issue" -- never the
local ledger.

Deliberately backend-neutral: all policy logic (item loading/validation,
sanitization, marker/label helpers, body rendering, plan-digest
computation, ledger read/write, lock acquire/release, and the top-level
orchestration) lives here; only the actual GitLab calls live in
`gitlab_issue.py`. This module never imports `graph.py`, and `graph.py`
must never import this module or reference `requirement_issues`/
`requirement_ledger` by name -- this feature is never wired into graph
dispatch (see `test_graph_module_never_references_requirement_issues` in
`tests/test_requirement_issues_cli.py`).

Stage A: items come from an operator-supplied file, never from an agent.
No `AgentContribution`/`SUBMIT_CONTRIBUTION_SCHEMA` involvement.

Re-entry semantics: the same issue is *reused* for a given item across
re-entries (matched by its per-item label), never re-created as a new
"generation". No local "has this been created" bookkeeping is ever
trusted over a fresh label search against the forge.

## Accepted residual risk: quick-action verification gap (v1, human-input-only)

Post-creation verification (`_process_item`'s `failures` checks) can only
catch a quick-action injection if it corrupted a field this module
actually re-reads and compares: labels, assignees, confidential, state,
title, project, author. GitLab quick actions with no corresponding
checkable field on the issue resource -- e.g. `/relate`, `/spend`,
`/subscribe`, `/due`, `/weight`, `/milestone`, `/epic` -- are *not*
independently detectable by this verification step even though the
description-line quick-action rejection in `sanitize_description` (step 2)
is the actual, primary control against them ever reaching GitLab in the
first place. This residual gap (an unverifiable quick action slipping
through if the primary line-prefix rejection were ever itself bypassed) is
accepted for v1 specifically because Stage A only accepts human-supplied
input (see module docstring above) -- there is no agent/LLM content path
into this module today. This acceptance does **not** extend to any future
stage that lets agent-authored or otherwise less-trusted content reach
`create_gitlab_issue`; that stage must not be authorized without
revisiting this gap (e.g. broader quick-action detection, or verification
against a full issue-notes/system-notes audit trail rather than just the
issue resource's own fields).
"""

