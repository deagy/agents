FIXED_LABEL = "agentic-sdlc"
LEDGER_SCHEMA_VERSION = 1
ITEMS_SCHEMA_VERSION = 1
DEFAULT_MAX_ITEMS = 50

_ITEM_KEY_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")
_LABEL_CHARSET_RE = re.compile(r"^[a-z0-9-]+$")

# See §3.3 step 1: control/line-separator characters a naive Cc/Cf-category
# filter misses but `str.splitlines()` still treats as line breaks, closing
# the gap between "what splitlines() sees" and "what a naive split('\n')
# check sees" at the source, before either is used. This set is meant to be
# the *complete*, authoritative list of splitlines()-recognized line breaks
# (beyond plain \n/\r) -- \x85 (NEL) is included for that reason even though
# it is not independently exploitable today (the splitlines()-based
# quick-action-line check below also happens to catch it via a different
# path); do not remove entries just because another check happens to also
# cover them.
_FORBIDDEN_DESC_CHARS = {"\x0b", "\x0c", "\x1c", "\x1d", "\x1e", "\x85", "\u2028", "\u2029"}

_MENTION_RE = re.compile(r"(?<!\w)@(\w[\w.-]*)")
_CROSS_REF_RE = re.compile(r"(?<!\w)([\w.-]+/[\w.-]+)?#(\d+)")

_PROVENANCE_BANNER = (
    "> Machine-generated by agentic-sdlc. Not a human-authored requirement. Not approval evidence."
)
_REF_LINE_PREFIX = "> ref "


class RequirementIssuesError(ValueError):
    """Structural/policy failure -- CLI maps this to exit code 1."""


class RequirementIssuesBlocked(ValueError):
    """Needs human resolution (ambiguous match, drift, lock held, digest
    mismatch mid-run) -- CLI maps this to exit code 2."""


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


